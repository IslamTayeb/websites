#!/usr/bin/env python3
"""Trims Google's Open Sans latin file (fonts/) to the characters the built
site renders and to the weights it uses (400-700), cutting it from 43 KB to
about 17 KB.

Run it after `npm run build` fails its font check, then build again:

    python3 scripts/subset-open-sans.py && npm run build

Needs fontTools with brotli (pip3 install fonttools brotli).

The weight axis keeps its 400 (default) and 700 masters, so every weight
the site uses interpolates exactly as before; only the unused 300 and 800
data goes. The trimmed font keeps its glyph names and the original
font-wide bounds.
Chrome draws with both; dropping names or recalculating the bounds shifts
glyph antialiasing even though every outline is unchanged.
"""

import hashlib
import html
import io
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = Path(__file__).resolve().parent.parent
source = root / 'fonts' / 'open-sans-latin.woff2'
css_path = root / 'styles' / 'open-sans-latin.css'
# Lightest and heaviest weights the site sets in Open Sans.
WEIGHTS = (400, 700)


def rendered_characters():
    chars = set()
    for page in (root / 'dist').rglob('*.html'):
        text = re.sub(r'<(script|style)\b.*?</\1>', '', page.read_text(), flags=re.S)
        chars |= {c for c in html.unescape(re.sub(r'<[^>]+>', ' ', text)) if c >= ' '}
    return chars


def unicode_range(code_points):
    runs = []
    for cp in sorted(code_points):
        if runs and cp == runs[-1][1] + 1:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    return ','.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in runs)


original = TTFont(source)
coverage = set(original.getBestCmap())
code_points = sorted(ord(c) for c in rendered_characters() if ord(c) in coverage)

options = subset.Options()
options.layout_features = ['*']
options.name_IDs = ['*']
options.glyph_names = True
options.notdef_outline = True
# Same input, same bytes: keep the original timestamp so the hash is stable.
# recalcBBoxes=False stops the save from recomputing the bounds restored below.
font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=code_points)
subsetter.subset(font)
font = instancer.instantiateVariableFont(font, {'wght': WEIGHTS})

# Keep the original font-wide bounds; see the docstring.
for table, fields in {
    'head': ['xMin', 'yMin', 'xMax', 'yMax'],
    'hhea': ['advanceWidthMax', 'minLeftSideBearing', 'minRightSideBearing', 'xMaxExtent'],
    'maxp': ['maxPoints', 'maxContours', 'maxCompositePoints', 'maxCompositeContours'],
}.items():
    for field in fields:
        setattr(font[table], field, getattr(original[table], field))

font.flavor = 'woff2'
buffer = io.BytesIO()
font.save(buffer)
data = buffer.getvalue()

# Fonts are cached forever, so the name changes whenever the bytes do.
name = f'open-sans-latin-{hashlib.sha1(data).hexdigest()[:8]}.woff2'
for old in (root / 'public' / 'fonts').glob('open-sans-latin-*.woff2'):
    if re.fullmatch(r'open-sans-latin-[0-9a-f]{8}\.woff2', old.name):
        old.unlink()
(root / 'public' / 'fonts' / name).write_bytes(data)

css_path.write_text(f"""/* Generated by scripts/subset-open-sans.py; do not edit.
   source coverage: {unicode_range(coverage)} */
/* latin */
@font-face {{
  font-family: 'Open Sans';
  font-style: normal;
  font-weight: {WEIGHTS[0]} {WEIGHTS[1]};
  font-stretch: 100%;
  font-display: swap;
  src: url(/fonts/{name}) format('woff2');
  unicode-range: {unicode_range(code_points)};
}}
""")
print(f'{name}: {len(code_points)} characters, {len(data) / 1024:.1f} KB')
